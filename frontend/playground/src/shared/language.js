const storageKey = "openutilityapi.language";
let language = "pt-BR";

export function getLanguage() { return language; }

export function setLanguage(value) {
  language = value === "en-US" ? value : "pt-BR";
  try { localStorage.setItem(storageKey, language); } catch { /* Storage may be unavailable. */ }
}

export function restoreLanguage() {
  try { language = localStorage.getItem(storageKey) === "en-US" ? "en-US" : "pt-BR"; }
  catch { language = "pt-BR"; }
}

export function t(text, locale = language) { return locale === "en-US" ? english[text] ?? text : text; }
